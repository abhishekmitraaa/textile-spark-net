"""Region move: builds post-restore.sql from the dumps (documentation/region-move-runbook-2026-11-28.md, step 5).

    python build-post-restore.py <dump dir>

Reads schema.sql, storage_schema.sql, auth_schema.sql and realtime_schema.sql (supabase db dump --linked, the last three
with --schema storage / auth / realtime) and writes post-restore.sql next to them. Run that against the new project
after roles, schema and data: it clears the rights a new project gives anon/authenticated by default, replays
production's grant lines and default privileges, and adds what the public dump leaves out (storage.objects policies,
the auth.users sign-up trigger, the realtime.messages channel rule, and the grants of the two halfvec functions).
"""
import re, sys
from pathlib import Path

d = Path(sys.argv[1])

def statements(path, start, keep=lambda s: True):
    out, cur = [], None
    for line in (d / path).read_text(encoding="utf-8").splitlines():
        if cur is None and line.startswith(start):
            cur = [line]
        elif cur is not None:
            cur.append(line)
        if cur is not None and line.rstrip().endswith(";"):
            s = "\n".join(cur)
            if keep(s):
                out.append(s)
            cur = None
    return out

schema = (d / "schema.sql").read_text(encoding="utf-8").splitlines()
acl = [l for l in schema if re.match(r'^(GRANT|REVOKE) .* ON (TABLE|SEQUENCE|FUNCTION) ', l) or l.startswith("ALTER DEFAULT PRIVILEGES")]
storage = statements("storage_schema.sql", "CREATE POLICY")
trigger = statements("auth_schema.sql", "CREATE OR REPLACE TRIGGER", lambda s: "on_auth_user_created" in s)
realtime = statements("realtime_schema.sql", "CREATE POLICY")
assert trigger, "auth dump has no on_auth_user_created trigger"

sql = f"""-- Generated by scripts/region-move/build-post-restore.py. Run once, after roles, schema and data.
begin;
revoke all on all tables in schema public, admin from anon, authenticated, service_role;
revoke all on all sequences in schema public, admin from anon, authenticated, service_role;
revoke all on all functions in schema public, admin from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on functions from anon, authenticated, service_role;
{chr(10).join(acl)}

-- The two functions whose arguments use extensions.halfvec: the CLI's dump leaves out their grants (production:
-- service_role only). Check this against production at the move; a new such function needs a line here.
revoke all on function public.halfvec_scale(extensions.halfvec, double precision) from public, anon, authenticated;
grant execute on function public.halfvec_scale(extensions.halfvec, double precision) to service_role;
revoke all on function public.match_products(text, extensions.halfvec, integer, double precision, double precision) from public, anon, authenticated;
grant execute on function public.match_products(text, extensions.halfvec, integer, double precision, double precision) to service_role;

{chr(10).join(storage)}

{chr(10).join(trigger)}

{chr(10).join(realtime)}
commit;
"""
(d / "post-restore.sql").write_text(sql, encoding="utf-8", newline="\n")
print(f"post-restore.sql: {len(acl)} grant lines, {len(storage)} storage policies, {len(trigger)} trigger, {len(realtime)} realtime policies")
