/** The /categories tile a seller sub-category belongs to, or null for a name this list doesn't know. */
export function tileForSellerSub(name: string | null | undefined): { topId: string; subLabel: string } | null {
  const hit = name ? SELLER_SUB_TILE[name] : undefined;
  return hit ? { topId: hit[0], subLabel: hit[1] } : null;
}
