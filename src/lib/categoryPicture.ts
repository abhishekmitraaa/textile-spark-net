// the website", and follow what the admin uploads).
//
// The picture of a category is its tile on /categories: the one set in Cosora-Admin › Category pictures
// (category_images, slot categories/<top>/<sub>), else the JPEG the app ships (categoryTileImages.ts). Every
// other surface that shows a category asks here, so changing it in the admin changes it on every page.
//
// Listings use a different list from the buyer's browse taxonomy: products.category_id points at the vendor
// upload taxonomy (data/sellerCategories.ts, seeded into public.categories by name). SELLER_SUB_TILE says which
// /categories tile each of those sub-categories is. `node scripts/category-image-slots-check.mjs` fails when a
// seller sub-category has no entry, or an entry names a tile that doesn't exist. JSX- and asset-free, so the
// script can load it.
// ─────────────────────────────────────────────────────────────

